/** Rows above the cap height, drawn from y - 1 upward (nearest row last). */
/** @type {Record<string, string[]>} */
export const ABOVE = {
  'Å': ['.###.'],
  'Ä': ['.#.#.'],
  'Ö': ['.#.#.'],
  'Ü': ['.#.#.'],
  'É': ['..##.'],
  'È': ['.##..'],
}

/** Characters drawn with another character's glyph. */
/** @type {Record<string, string>} */
export const ALIAS = {
  'Ä': 'A',
  'Ö': 'O',
  'Ü': 'U',
  'É': 'E',
  'È': 'E',
  '–': '-',
  '’': "'",
  '‘': "'",
  '“': '"',
  '”': '"',
  '•': '·',
  '✕': '×',
  '✗': '×',
  '‹': '<',
  '›': '>',
  ' ': ' ',
}

/** @param {string} ch an upper-case character */
function glyph(ch) {
  return GLYPHS[ch] ?? GLYPHS[ALIAS[ch] ?? '?'] ?? GLYPHS['?']
}

/**
 * A character's seven glyph rows ('#' = lit), after upper-casing. Unknown
 * characters draw as '?'.
 * @param {string} ch
 * @returns {string[]}
 */
export function glyphRows(ch) {
  return glyph(ch.toUpperCase())
}

/**
 * The rows a character draws above the cap height (usually none).
 * @param {string} ch
 * @returns {string[]}
 */
export function glyphAbove(ch) {
  return ABOVE[ch.toUpperCase()] ?? []
}

/**
 * Width of a line of text in font pixels (at size 1).
 * @param {string} text
 * @returns {number}
 */
export function textWidth(text) {
  let w = 0
  for (const ch of text.toUpperCase()) w += glyph(ch)[0].length + 1
  return Math.max(0, w - 1)
}

/**
 * Draw one line of text with its top-left at (x, y), one font pixel per
 * logical pixel. `shadow` adds the hard drop shadow one pixel down-right.
 * @param {CanvasRenderingContext2D} ctx
 * @param {string} text
 * @param {number} x
 * @param {number} y
 * @param {string} color
 * @param {string} [shadow]
 */
export function drawText(ctx, text, x, y, color, shadow) {
  drawBigText(ctx, text, x, y, 1, color, shadow)
}

/**
 * Text with every font pixel drawn as an n×n block (titles). The shadow is
 * n pixels down-right.
 * @param {CanvasRenderingContext2D} ctx
 * @param {string} text
 * @param {number} x
 * @param {number} y
 * @param {number} n pixels per font pixel (whole number)
 * @param {string} color
 * @param {string} [shadow]
 */
export function drawBigText(ctx, text, x, y, n, color, shadow) {
  const t = text.toUpperCase()
  /** @param {number} ox @param {number} oy @param {string} fill */
  const pass = (ox, oy, fill) => {
    ctx.fillStyle = fill
    let cx = x + ox
    for (const ch of t) {
      const up = ABOVE[ch] ?? []
      const rows = up.length ? [...up, ...glyph(ch)] : glyph(ch)
      const w = rows[0].length
      for (let gy = 0; gy < rows.length; gy++) {
        const row = rows[gy]
        // One rect per horizontal run.
        let gx = 0
        while (gx < w) {
          if (row[gx] !== '#') { gx++; continue }
          const start = gx
          while (gx < w && row[gx] === '#') gx++
          ctx.fillRect(cx + start * n, y + oy + (gy - up.length) * n, (gx - start) * n, n)
        }
      }
      cx += (w + 1) * n
    }
  }
  if (shadow) pass(n, n, shadow)
  pass(0, 0, color)
}

/**
 * Width of `drawBigText` output.
 * @param {string} text
 * @param {number} n
 * @returns {number}
 */
export function bigTextWidth(text, n) {
  return textWidth(text) * n
}

/**
 * Break text into lines no wider than `maxWidth` font pixels. Newlines in
 * the text start new lines.
 * @param {string} text
 * @param {number} maxWidth
 * @returns {string[]}
 */
export function wrapText(text, maxWidth) {
  const lines = []
  for (const para of text.split('\n')) {
    const words = para.split(/\s+/).filter(Boolean)
    let line = ''
    for (const word of words) {
      const next = line ? line + ' ' + word : word
      if (textWidth(next) <= maxWidth || !line) line = next
      else {
        lines.push(line)
        line = word
      }
    }
    lines.push(line)
  }
  return lines
}
